"""Tests for the committed notebooks.

The notebooks are generated by ``tools/make_notebooks.py`` and executed by
``tools/run_notebooks.py``. Jupyter's own kernel supervisor cannot run here
(it needs the system temp directory, which the sandbox denies), so the runner
executes the cells in a shared namespace. That still catches syntax errors,
bad imports, wrong attribute names and failing assertions.
"""

from __future__ import annotations

import json
import subprocess
import sys
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
NOTEBOOKS = REPO_ROOT / "notebooks"
TOOLS = REPO_ROOT / "tools"

sys.path.insert(0, str(TOOLS))

import make_notebooks  # noqa: E402
import run_notebooks  # noqa: E402


class TestNotebookStructure(unittest.TestCase):
    def test_both_notebooks_exist(self) -> None:
        self.assertTrue((NOTEBOOKS / "01_exploration.ipynb").is_file())
        self.assertTrue((NOTEBOOKS / "02_analysis.ipynb").is_file())

    def test_notebooks_are_nbformat_4(self) -> None:
        for path in sorted(NOTEBOOKS.glob("*.ipynb")):
            with self.subTest(path=path.name):
                data = json.loads(path.read_text(encoding="utf-8"))
                self.assertEqual(data["nbformat"], 4)
                self.assertIn("cells", data)
                self.assertTrue(data["cells"])

    def test_cell_sources_are_lists_of_lines(self) -> None:
        """nbformat requires `source` to be a list of strings, not one string."""
        for path in sorted(NOTEBOOKS.glob("*.ipynb")):
            data = json.loads(path.read_text(encoding="utf-8"))
            for cell in data["cells"]:
                with self.subTest(path=path.name, cell=cell["cell_type"]):
                    self.assertIsInstance(cell["source"], list)
                    for line in cell["source"]:
                        self.assertIsInstance(line, str)

    def test_no_stored_outputs(self) -> None:
        """Outputs are stripped so diffs stay small and reviewable."""
        for path in sorted(NOTEBOOKS.glob("*.ipynb")):
            data = json.loads(path.read_text(encoding="utf-8"))
            for cell in data["cells"]:
                if cell["cell_type"] == "code":
                    with self.subTest(path=path.name):
                        self.assertEqual(cell.get("outputs", []), [])

    def test_declares_a_python_kernel(self) -> None:
        for path in sorted(NOTEBOOKS.glob("*.ipynb")):
            data = json.loads(path.read_text(encoding="utf-8"))
            self.assertEqual(data["metadata"]["kernelspec"]["language"], "python", path.name)


class TestNotebookExecution(unittest.TestCase):
    def test_all_notebooks_execute(self) -> None:
        """Running every code cell must succeed end to end."""
        rc = run_notebooks.main([])
        self.assertEqual(rc, 0, "notebook execution failed; see stderr for the cell")

    def test_check_mode_validates_json(self) -> None:
        rc = run_notebooks.main(["--check"])
        self.assertEqual(rc, 0)

    def test_generator_is_idempotent(self) -> None:
        """Re-running the generator must not change the committed notebooks."""
        before = {p.name: p.read_text(encoding="utf-8") for p in sorted(NOTEBOOKS.glob("*.ipynb"))}
        make_notebooks.main()
        after = {p.name: p.read_text(encoding="utf-8") for p in sorted(NOTEBOOKS.glob("*.ipynb"))}
        self.assertEqual(before, after)


class TestNotebookGenerator(unittest.TestCase):
    def test_builds_valid_nbformat_dict(self) -> None:
        nb = make_notebooks.notebook([make_notebooks.code("x = 1")])
        self.assertEqual(nb["nbformat"], 4)
        self.assertEqual(nb["cells"][0]["cell_type"], "code")

    def test_code_cell_strips_surrounding_blank_lines(self) -> None:
        cell = make_notebooks.code("\n\nx = 1\n\n")
        # Leading/trailing blank lines are removed; the result is the single
        # source line with no trailing newline.
        self.assertEqual(cell["source"], ["x = 1"])

    def test_multiline_source_keeps_inner_newlines(self) -> None:
        cell = make_notebooks.code("x = 1\ny = 2")
        self.assertEqual(cell["source"], ["x = 1\n", "y = 2"])

    def test_markdown_cell_has_no_outputs_key(self) -> None:
        cell = make_notebooks.markdown("# Title")
        self.assertNotIn("outputs", cell)

    def test_generator_runs_as_a_script(self) -> None:
        result = subprocess.run(
            [sys.executable, str(TOOLS / "make_notebooks.py")],
            capture_output=True,
            text=True,
            cwd=str(REPO_ROOT),
        )
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == "__main__":
    unittest.main()
